/** 상품명으로 위험 부류를 본다. 확실하지 않으면 LOW 로 두되 절대 "안전 확정"이 아니다. */
export function judgeRisk(name: string): RiskInfo {
  const n = (name || "").toLowerCase().replace(/\s+/g, "");
  for (const r of RULES) {
    if (r.words.some((w) => n.includes(w.toLowerCase()))) {
      return { level: r.level, category: r.category, why: r.why, check: r.check };
    }
  }
  return {
    level: "LOW",
    category: "일반 생활잡화",
    why: "특별한 인증·규제 신호가 보이지 않습니다",
    check: "그래도 상품 페이지의 KC 표시는 한 번 확인하세요",
  };
}

